"""
Step 1: clean data + EDA + baseline model.

Run from the project root:   python notebooks/01_eda_baseline.py
(The '# %%' lines are cell markers, so you can also open this file in VS Code
and run it cell by cell like a Jupyter notebook.)
"""
# %% Imports
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parent.parent))  # so "src" can be imported

import matplotlib
matplotlib.use("Agg")  # save figures to files instead of opening windows
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.dummy import DummyClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (average_precision_score, confusion_matrix,
                             f1_score, precision_score, recall_score)
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from src.data_prep import ROOT, TARGET, feature_columns, load_clean

OUT = ROOT / "artifacts" / "eda"
OUT.mkdir(parents=True, exist_ok=True)

# %% 1. Load + clean
df, report = load_clean()
features = feature_columns(df)
pd.Series(report).to_json(OUT / "cleaning_report.json", indent=2)

# %% 2. EDA - class balance
counts = df[TARGET].value_counts().sort_index()
print("\nClass balance (0 = unsafe, 1 = safe):")
print(counts.to_string(), f"\nSafe share: {df[TARGET].mean():.1%}")

fig, ax = plt.subplots(figsize=(4, 3))
ax.bar(["unsafe (0)", "safe (1)"], counts.values, color=["#c0392b", "#27ae60"])
ax.set_title("Class balance")
fig.tight_layout()
fig.savefig(OUT / "class_balance.png", dpi=120)
plt.close(fig)

# %% 3. EDA - summary stats, skewness, and a "looks synthetic?" check
summary = df[features].describe().T
summary["skew"] = df[features].skew()
summary.to_csv(OUT / "feature_summary.csv")
print("\nMost skewed features:")
print(summary["skew"].sort_values(ascending=False).head(5).round(2).to_string())

# Real lab data usually has lots of exact repeats and heavy tails. Features that are
# roughly uniform between a hard min and max suggest the data was generated by a script.
print("\nNumber of distinct values per feature (low = values are rounded/discretised):")
print(df[features].nunique().sort_values().to_string())

# %% 4. EDA - which chemicals differ between safe and unsafe samples?
# Correlation with the label tells us the linear relationship (like in linear regression).
corr_target = df[features + [TARGET]].corr()[TARGET].drop(TARGET).sort_values()
print("\nCorrelation of each feature with is_safe (negative = more of it -> less safe):")
print(corr_target.round(3).to_string())
corr_target.to_csv(OUT / "corr_with_target.csv")

fig, ax = plt.subplots(figsize=(6, 6))
corr_target.plot.barh(ax=ax, color=np.where(corr_target < 0, "#c0392b", "#27ae60"))
ax.set_title("Correlation with is_safe")
fig.tight_layout()
fig.savefig(OUT / "corr_with_target.png", dpi=120)
plt.close(fig)

# Mean of every feature per class, as a ratio (unsafe / safe).
# A big ratio means that chemical is much higher in unsafe water.
means = df.groupby(TARGET)[features].mean().T
means["ratio_unsafe_over_safe"] = means[0] / means[1].replace(0, np.nan)
means.to_csv(OUT / "class_means.csv")
print("\nChemicals most elevated in unsafe water:")
print(means["ratio_unsafe_over_safe"].sort_values(ascending=False).head(6).round(2).to_string())

# %% 5. EDA - correlation between features (multicollinearity check)
cm = df[features].corr()
fig, ax = plt.subplots(figsize=(9, 8))
im = ax.imshow(cm, cmap="coolwarm", vmin=-1, vmax=1)
ax.set_xticks(range(len(features)), features, rotation=90)
ax.set_yticks(range(len(features)), features)
fig.colorbar(im)
ax.set_title("Feature correlation")
fig.tight_layout()
fig.savefig(OUT / "feature_correlation.png", dpi=120)
plt.close(fig)

# %% 6. EDA - histograms per class for every feature
fig, axes = plt.subplots(4, 5, figsize=(18, 11))
for ax, col in zip(axes.ravel(), features):
    ax.hist(df.loc[df[TARGET] == 0, col], bins=30, alpha=0.6, density=True, label="unsafe", color="#c0392b")
    ax.hist(df.loc[df[TARGET] == 1, col], bins=30, alpha=0.6, density=True, label="safe", color="#27ae60")
    ax.set_title(col, fontsize=10)
axes[0, 0].legend()
fig.tight_layout()
fig.savefig(OUT / "feature_hist_by_class.png", dpi=110)
plt.close(fig)

# %% 7. Baseline models with STRATIFIED 5-fold cross-validation
# Stratified = every fold keeps the same ~11% safe share, so the rare class
# is never missing from a fold.
X, y = df[features].values, df[TARGET].values
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

candidates = {
    # Always predicts "unsafe". Shows why accuracy is misleading here.
    "Dummy (always unsafe)": DummyClassifier(strategy="most_frequent"),
    # Logistic regression with no imbalance handling.
    "LogReg (no weights)": make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000)),
    # class_weight='balanced' makes mistakes on the rare "safe" class cost more
    # (roughly 8x), so the model can't just ignore it.
    "LogReg (class_weight=balanced)": make_pipeline(
        StandardScaler(), LogisticRegression(max_iter=2000, class_weight="balanced")),
}

rows, oof_store = [], {}
for name, model in candidates.items():
    # "Out-of-fold" predictions: each row is predicted by a model that never saw it.
    proba = cross_val_predict(model, X, y, cv=cv, method="predict_proba")[:, 1]
    pred = (proba >= 0.5).astype(int)
    oof_store[name] = (y, pred)
    rows.append({
        "model": name,
        "accuracy": (pred == y).mean(),            # shown only to demonstrate the trap
        "precision_safe": precision_score(y, pred, zero_division=0),
        "recall_safe": recall_score(y, pred, zero_division=0),
        "F1_safe": f1_score(y, pred, zero_division=0),
        "PR_AUC": average_precision_score(y, proba),  # threshold-free; chance level = safe share
    })

results = pd.DataFrame(rows).set_index("model").round(3)
results.to_csv(OUT / "baseline_results.csv")
print("\nBaseline results (minority class = safe, pooled over 5 folds):")
print(results.to_string())
print(f"\nPR-AUC of a random guesser would be about {y.mean():.3f} (the safe share).")

# %% 8. Confusion matrix of the weighted baseline
yt, yp = oof_store["LogReg (class_weight=balanced)"]
tn, fp, fn, tp = confusion_matrix(yt, yp).ravel()
print(f"\nConfusion matrix (weighted LogReg): TN={tn} FP={fp} FN={fn} TP={tp}")

# %% 9. Largest logistic-regression coefficients (a first look at influential chemicals)
# Features were standardised, so coefficients are comparable: bigger |coef| = stronger push.
final = candidates["LogReg (class_weight=balanced)"].fit(X, y)
coefs = pd.Series(final[-1].coef_[0], index=features).sort_values()
coefs.to_csv(OUT / "logreg_coefficients.csv")
print("\nLogReg coefficients (negative = pushes toward 'unsafe'):")
print(coefs.round(2).to_string())
print("\nDone. Figures and tables are in artifacts/eda/")
